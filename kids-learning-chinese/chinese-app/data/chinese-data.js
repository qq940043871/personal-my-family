/** 获取按课程组织的词语 */
export function getWordsByLesson(book, lesson, type) {
  const bookData = wordsByLesson[book] || [];
  if (!lesson && !type) return bookData;
  return bookData.filter(s => {
    if (lesson && s.lesson !== lesson) return false;
    if (type && s.type !== type) return false;
    return true;
  });
}

/** 获取某课的全部词语（扁平数组） */
export function getLessonWords(book, lesson) {
  const sections = getWordsByLesson(book, lesson);
  const words = [];
  sections.forEach(s => words.push(...s.words));
  return [...new Set(words)];
}

